root <- "/private/tmp/mixeff-cran-20261026-64ptil"
pkg <- file.path(root, "candidate")
lib <- file.path(root, "final-check", "mixeff.Rcheck")
.libPaths(c(lib, file.path(root, "reference-lme4"), file.path(root, "check-deps"), .libPaths()))
library(mixeff)
stopifnot(normalizePath(find.package("mixeff")) == normalizePath(file.path(lib, "mixeff")))
stopifnot(packageVersion("lme4") >= "2.1.0")
cat("Package:", find.package("mixeff"), "\nlme4:", as.character(packageVersion("lme4")), "\n")
Sys.unsetenv(c("MIXEFF_APHANTASIA_JOINT", "MIXEFF_RUN_APHANTASIA_STRESS", "MIXEFF_APHANTASIA_JOINT_PROOF", "MIXEFF_APHANTASIA_JOINT_BUDGET"))
Sys.setenv(NOT_CRAN="true", MIXEFF_RUN_SLOW_PARITY="true", MIXEFF_RUN_APHANTASIA="true")
started <- proc.time()[["elapsed"]]
res <- testthat::test_dir(file.path(pkg,"tests","testthat"), package="mixeff", load_package="installed", stop_on_failure=FALSE, reporter="silent")
saveRDS(res, file.path(root,"final-suite-results.rds"))
df <- as.data.frame(res)
fails <- sum(df$failed)+sum(df$error)
cat(sprintf("FINAL SUITE: %d pass / %d fail / %d warning / %d skip in %.0fs\n",sum(df$passed),fails,sum(df$warning),sum(df$skipped),proc.time()[["elapsed"]]-started))
if(fails) print(df[df$failed>0 | df$error,c("file","test","failed","error")])
skips <- unlist(lapply(res,function(t) vapply(Filter(function(x) inherits(x,"expectation_skip"),t$results),conditionMessage,character(1))))
cat("SKIPS:\n",paste(unique(skips),collapse="\n"),"\n")
allowed <- c("is not installed","pandoc is unavailable","Set MIXEFF_RUN_APHANTASIA_STRESS=true","Set MIXEFF_RUN_APHANTASIA_JOINT_PROOF=true","offset invariance is asserted only for a certified joint fit","empty test")
unexpected <- skips[!vapply(skips,function(m) any(vapply(allowed,grepl,logical(1),x=m,fixed=TRUE)),logical(1))]
cat("Unexpected skips:",length(unexpected),"\n")
lints <- lintr::lint_package(pkg)
print(lints)
cat("Lints:",length(lints),"\n")
Sys.setenv(MIXEFF_RUN_APHANTASIA_VIGNETTE="true")
out <- file.path(root,"final-live")
dir.create(out,showWarnings=FALSE)
rendered <- rmarkdown::render(file.path(pkg,"vignettes","articles","reproducing-aphantasia.Rmd"),output_format=rmarkdown::html_vignette(),output_dir=out,envir=new.env(parent=globalenv()),quiet=TRUE)
complete <- any(grepl("</html>",readLines(rendered,warn=FALSE),fixed=TRUE))
cat("LIVE HTML complete:",complete,"\n")
stopifnot(fails==0,length(unexpected)==0,length(lints)==0,complete)
